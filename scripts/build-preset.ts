import { readFile, writeFile } from 'node:fs/promises';

// Keep the human-edited entry list independent of bundle-patch indentation.
// Generate a literal declaration, not a runtime include with an ambiguous base URL.
const source = new URL('../presets/snapcompact.yml', import.meta.url);
const target = new URL('../cordis.patch.yml', import.meta.url);
const entries = (await readFile(source, 'utf8')).trimEnd();
// The settings row lives on the profile plane on purpose: DSH only projects
// volatile Config fields of profile entries into the settings form, while the
// compaction plugin itself must stay inside the opt-in preset.
const header = `# Generated by scripts/build-preset.ts; edit presets/snapcompact.yml instead.
# The carrier row exists because the browser module scanner only reads
# \`dsh.client\` from Loader entries whose name is a bare package specifier.
- insert:
    - id: snapcompact-ui
      name: dsh-snapcompact
      config:
        role: ui
    - id: snapcompact-settings
      name: dsh-snapcompact/settings
- insert:
    - id: preset-snapcompact
      name: '@deepseek-ai/dsh-agent-preset'
      config:
        id: snapcompact
        name: Snapcompact
        description: 'Standard mode with Snapcompact bitmap-frame compaction and exact-history recall.'
        order: 20
        plugins:
`;
await writeFile(
  target,
  header +
    entries
      .split('\n')
      .map((line) => (line.trimEnd() === '' ? '' : `          ${line.trimEnd()}`))
      .join('\n') +
    '\n',
);
