import { readFile, writeFile } from 'node:fs/promises';
import { PRESET_VARIANTS } from './preset-variants.ts';

// Keep the human-edited entry lists independent of bundle-patch indentation.
// Generate literal declarations, not a runtime include with an ambiguous base URL.
const sourceDir = new URL('../presets/', import.meta.url);
const target = new URL('../cordis.patch.yml', import.meta.url);
const checkOnly = process.argv.includes('--check');

// The settings row lives on the profile plane on purpose: DSH only projects
// volatile Config fields of profile entries into the settings form, while the
// compaction plugin itself must stay inside the opt-in preset.
//
// Preset names and descriptions stay English. The Host localizes only its own
// shipped preset ids; third-party name/description are rendered verbatim (see
// `presetDisplayText` in @deepseek-ai/dsh-agent-preset-registry), so there is no
// bilingual variant to hook into. Keep the copy self-explanatory for readers
// whose UI runs in another language.
const header = `# Generated by scripts/build-preset.ts; edit presets/*.yml instead.
# The carrier row exists because the browser module scanner only reads
# \`dsh.client\` from Loader entries whose name is a bare package specifier.
- insert:
    - id: snapcompact-ui
      name: dsh-snapcompact
      config:
        role: ui
    - id: snapcompact-settings
      name: dsh-snapcompact/settings
- insert:
`;

function indent(text: string): string {
  return text
    .split('\n')
    .map((line) => (line.trimEnd() === '' ? '' : `          ${line.trimEnd()}`))
    .join('\n');
}

const declarations = await Promise.all(
  PRESET_VARIANTS.map(async (variant) => {
    const entries = (await readFile(new URL(variant.source, sourceDir), 'utf8')).trimEnd();
    return `    - id: preset-${variant.id}
      name: '@deepseek-ai/dsh-agent-preset'
      config:
        id: ${variant.id}
        name: ${variant.name}
        description: '${variant.description}'
        # The registry sorts presets by numeric order, so this variant sits
        # right after the official preset it mirrors.
        order: ${String(variant.order)}
        plugins:
${indent(entries)}`;
  }),
);

const output = `${header}${declarations.join('\n')}\n`;

if (checkOnly) {
  const existing = await readFile(target, 'utf8').catch(() => undefined);
  if (existing !== output) {
    throw new Error('cordis.patch.yml is stale; run pnpm build');
  }
} else {
  await writeFile(target, output);
}
