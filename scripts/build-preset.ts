import { readFile, writeFile } from 'node:fs/promises';

// Keep the human-edited entry list independent of bundle-patch indentation.
// Generate a literal declaration, not a runtime include with an ambiguous base URL.
const source = new URL('../presets/snapcompact.yml', import.meta.url);
const target = new URL('../cordis.patch.yml', import.meta.url);
const entries = (await readFile(source, 'utf8')).trimEnd();
const header = `# Generated by scripts/build-preset.ts; edit presets/snapcompact.yml instead.
- insert:
    - id: preset-snapcompact
      name: '@deepseek-ai/dsh-agent-preset'
      config:
        id: snapcompact
        name: Snapcompact
        description: 'Recoverable visual/text compaction with standard coding tools.'
        order: 20
        plugins:
`;
await writeFile(
  target,
  header +
    entries
      .split('\n')
      .map((line) => `          ${line}`)
      .join('\n') +
    '\n',
);
